import { dump } from 'js-yaml';
import { normAddress } from './channels.js';

const YAML_OPTS = { sortKeys: true, lineWidth: -1, noRefs: true };

function sourceLines(meta) {
  return Object.keys(meta).sort().map(exp => {
    const m = meta[exp];
    return `# channels: ${exp} ${m.label}@${m.version ? m.version.slice(0, 7) : 'unknown'}`;
  });
}

function compact(obj) {
  const out = {};
  for (const [k, v] of Object.entries(obj)) {
    if (v === undefined || v === null || v === '' || (Array.isArray(v) && !v.length)) continue;
    out[k] = v;
  }
  return out;
}

// One component as map.yaml shows it: resolved properties, inputs and outputs.
export function componentRecord(c) {
  return compact({
    ...c.props,
    note: c.path,
    model: c.model,
    beam_from: c.inputs.beam.map(b => (b.item ? compact({ unit: b.unit, item: b.item }) : b.unit)),
    rf_from: c.inputs.rf.map(r => compact({ unit: r.unit, item: r.item })),
    control_from: c.inputs.control.map(x => (x.channel
      ? { unit: x.unit, channel: x.channel, experiment: x.experiment, address: x.address }
      : x.experiment ? { experiment: x.experiment } : compact({ unit: x.unit, item: x.item }))),
    feeds: c.feeds,
    drives: c.drives,
  });
}

const CHANNEL_KEYS = ['kind', 'address', 'unresolved', 'board', 'unit', 'source', 'comment', 'disabled', 'also_declared_at', 'used_by'];

// One channel as map.yaml shows it. A source's `extra` values sit beside the
// standard keys, which they never replace.
export function channelRecord(e) {
  const d = e.primary;
  const extra = Object.fromEntries(Object.entries(d.extra ?? {}).filter(([k]) => !CHANNEL_KEYS.includes(k) && k !== 'name' && k !== 'experiment'));
  return compact({
    ...extra,
    kind: d.kind,
    address: d.address,
    unresolved: d.address ? null : d.unresolved,
    board: d.board,
    unit: e.unit,
    source: d.source?.label,
    comment: d.comment,
    disabled: d.disabled,
    also_declared_at: e.decls.filter(x => x !== d).map(x => x.source?.label).filter(Boolean),
    used_by: e.usedBy,
  });
}

export function renderMapYaml(graph) {
  const components = {};
  for (const c of Object.values(graph.components)) components[c.name] = componentRecord(c);
  const models = {};
  for (const m of Object.values(graph.models)) {
    models[m.name] = compact({ ...m.props, note: m.path, extends: m.extends, instances: m.instances });
  }
  const channels = {};
  for (const [exp, table] of Object.entries(graph.channels)) {
    channels[exp] = {};
    for (const e of Object.values(table)) channels[exp][e.name] = channelRecord(e);
  }
  const problems = graph.problems.map(p => (p.subject ? `${p.subject}: ${p.message}` : p.message));
  const header = [
    '# GENERATED by the experiment-map plugin. Edit component and model notes, not this file.',
    '# Regenerate: node .obsidian/plugins/experiment-map/cli.js sync',
    ...sourceLines(graph.sourceMeta ?? {}),
  ].join('\n');
  return `${header}\n${dump({ components, models, channels, problems }, YAML_OPTS)}`;
}

const esc = s => String(s ?? '').replace(/\|/g, '\\|');

const kindLabel = k => String(k).replace(/_/g, ' ');
const sourceLink = s => (s?.url ? `[${s.label}](${s.url})` : s?.label ?? '');

export function renderChannelPage(experiment, src, graph) {
  const table = graph.channels[experiment] ?? {};
  const from = src.url ? `[${src.label}](${src.url})` : src.label;
  const out = [];
  out.push(`> [!info] Generated by experiment-map from ${from}${src.version ? ` at \`${src.version.slice(0, 7)}\`` : ''}.`);
  out.push('> Edit the channel source or the component notes, not this page.', '');
  if (src.missing) {
    out.push(`No copy of ${src.label} has been fetched yet. Run "Experiment map: Sync" while online.`, '');
    return out.join('\n');
  }
  // In the order the source lists them.
  const order = new Map(src.parsed.channels.map((ch, i) => [ch, i]));
  const entries = Object.values(table).sort((a, b) => order.get(a.decls[0]) - order.get(b.decls[0]));
  for (const e of entries) {
    out.push(`## ${e.name}`);
    for (const d of [e.primary, ...e.decls.filter(x => x !== e.primary)]) {
      const parts = [`**${kindLabel(d.kind)}**`, d.address ? `\`${d.address}\`` : `\`${d.unresolved ?? '?'}\` (address not resolved)`];
      if (d === e.primary && e.unit) parts.push(`[[${e.unit}]]`);
      for (const [k, v] of Object.entries(d.extra ?? {})) parts.push(`${k}: ${v}`);
      out.push(`- ${parts.join(' · ')}${d.disabled.length ? ` · ⚠ ${d.disabled.join(', ')}` : ''}`);
      if (d.comment) out.push(`  - comment: ${d.comment}`);
      if (d.source?.label) out.push(`  - source: ${sourceLink(d.source)}`);
    }
    if (e.usedBy.length) out.push(`- used by: ${e.usedBy.map(n => `[[${n}]]`).join(', ')}`);
    out.push('');
  }
  if (src.parsed.boards.length) {
    const owners = new Map(Object.values(graph.components)
      .filter(c => c.props.type === 'controller' && c.props.address && (c.props.experiment ?? []).includes(experiment))
      .map(c => [normAddress(c.props.address), c.name]));
    out.push('# Boards', '', '| name | address | note | controller |', '|---|---|---|---|');
    for (const b of src.parsed.boards) out.push(`| ${esc(b.name)} | ${esc(b.address ?? '?')} | ${esc(b.comment)} | ${owners.has(b.address) ? `[[${owners.get(b.address)}]]` : ''} |`);
    out.push('');
  }
  if (src.parsed.appendix) out.push(src.parsed.appendix.replace(/\n+$/, ''), '');
  return out.join('\n');
}

export function renderSyncReport(graph) {
  const lines = ['> [!info] Generated by experiment-map. Fix each problem in the note it names, then sync again.', ''];
  const n = graph.problems.length;
  if (!n) {
    lines.push('No problems.');
  } else {
    lines.push(`**${n} problem${n === 1 ? '' : 's'}**`, '');
    for (const p of graph.problems) lines.push(`- ${p.subject ? `[[${p.subject}]]: ` : ''}${p.message}`);
  }
  return `${lines.join('\n')}\n`;
}
